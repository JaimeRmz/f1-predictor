#!/usr/bin/env python3
"""Attribute a built JS chunk's bytes to packages / source files using its sourcemap.

No dependencies: decodes the sourcemap's VLQ `mappings`, then assigns every
generated byte range between consecutive mapping segments to that segment's source
file. Approximate (minified identifiers and glue between segments are charged to the
preceding segment's source) but good to a few percent for "what is in this chunk".

Build first, OUTSIDE the repo so nothing in frontend/ changes:
    cd frontend && npx vite build --outDir <tmp>/dist-audit --emptyOutDir --sourcemap
Run:
    python analysis/07_bundle_attribution.py <tmp>/dist-audit/assets/index-XXXX.js [top_n]
"""
import collections
import json
import re
import sys

B64 = {c: i for i, c in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/")}


def vlq_decode(seg):
    out, shift, val = [], 0, 0
    for ch in seg:
        d = B64[ch]
        val += (d & 31) << shift
        if d & 32:
            shift += 5
        else:
            out.append(-(val >> 1) if val & 1 else val >> 1)
            shift = val = 0
    return out


def attribute(js_path):
    sm = json.load(open(js_path + ".map", encoding="utf8"))
    code_lines = open(js_path, encoding="utf8").read().split("\n")
    sources = sm["sources"]
    per_src = collections.Counter()
    src_idx = 0
    for gl, line in enumerate(sm["mappings"].split(";")):
        if gl >= len(code_lines):
            break
        n = len(code_lines[gl].encode("utf8"))
        segs, col, cur_src = [], 0, None
        sidx = src_idx
        for seg in line.split(",") if line else []:
            v = vlq_decode(seg)
            col += v[0]
            if len(v) >= 4:
                sidx += v[1]
            segs.append((col, sidx if len(v) >= 4 else None))
        src_idx = sidx
        if not segs:
            per_src["(unmapped)"] += n
            continue
        per_src["(unmapped)"] += segs[0][0]
        for i, (c, s) in enumerate(segs):
            end = segs[i + 1][0] if i + 1 < len(segs) else n
            per_src[sources[s] if s is not None else "(unmapped)"] += max(0, end - c)
    return per_src


def group(name):
    m = re.search(r"node_modules/((?:@[^/]+/)?[^/]+)", name.replace("\\", "/"))
    if m:
        return m.group(1)
    if name == "(unmapped)":
        return name
    n = name.replace("\\", "/")
    return "src/" + n.split("/src/")[-1] if "/src/" in n else n


if __name__ == "__main__":
    path = sys.argv[1]
    top = int(sys.argv[2]) if len(sys.argv) > 2 else 15
    per_src = attribute(path)
    tot = sum(per_src.values())
    by_pkg = collections.Counter()
    for k, v in per_src.items():
        by_pkg[group(k)] += v
    print(f"{path.split('/')[-1]}: {tot/1024:.1f} kB attributed")
    for k, v in by_pkg.most_common(top):
        print(f"  {v/1024:8.1f} kB  {v/tot*100:5.1f}%  {k}")
