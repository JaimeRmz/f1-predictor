#!/usr/bin/env python3
"""Write the backtest figures the site shows, from the backtest outputs. Nothing is typed by hand.

    python analysis/29_emit_frontend_figures.py [--source rolled|history] [--check]

--source rolled   (default) analysis/out/rolled/  : winner_hit_ci.json, model_page_figures.json
--source history  analysis/out/history/pre-roll-forward/ (the figures published before the roll-forward fix)
--check           do not write; exit 1 if the files on disk differ from what this source would produce. Running
                  `--source history --check` on the commit BEFORE the figures were regenerated proves the templates below reproduce the
                  published files exactly (so a regeneration changes numbers and nothing else).

Writes:
  frontend/src/lib/homeModel.js     only the BACKTEST and BACKTEST_FULL blocks (hits and 95% Wilson ranges)
  frontend/src/lib/modelFigures.generated.js   MODEL_FIGURES for the Model page (ROC-AUC, recall, precision, top-10 overlap, the 43-race hit table)
"""
import argparse
import json
import os
import re
import subprocess
import sys

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
HOME = os.path.join(REPO, "frontend", "src", "lib", "homeModel.js")
GEN = os.path.join(REPO, "frontend", "src", "lib", "modelFigures.generated.js")
SRC = {"rolled": os.path.join(REPO, "analysis", "out", "rolled"), "history": os.path.join(REPO, "analysis", "out", "history", "pre-roll-forward")}

ap = argparse.ArgumentParser()
ap.add_argument("--source", choices=SRC, default="rolled")
ap.add_argument("--check", action="store_true")
args = ap.parse_args()
d = SRC[args.source]
hit = json.load(open(os.path.join(d, "winner_hit_ci.json")))


def row(cond, method):
    r = hit[f"{cond}|all_43|{method}"]
    return r["hits"], [round(float(r["wilson"][0]), 2), round(float(r["wilson"][1]), 2)], r["races"]


def ci(c):
    return f"[{c[0]:.2f}, {c[1]:.2f}]"


n = row("b_predicted_quali", "model")[2]
mh, mc, _ = row("b_predicted_quali", "model")
sh, sc, _ = row("b_predicted_quali", "prior_standings")
backtest = f"""export const BACKTEST = {{
  races: {n},
  model: {{ hits: {mh}, ci: {ci(mc)} }},
  standingsLeader: {{ hits: {sh}, ci: {ci(sc)} }},
}};"""


def r(cond, method, label, extra=""):
    h, c, _ = row(cond, method)
    return f'      {{ key: "{ {"prior_standings": "standings", "prior_constructor": "constructor", "prior_grid": "grid", "model": "model"}[method] }", label: "{label}", hits: {h}, ci: {ci(c)}{extra} }},'


full = f"""export const BACKTEST_FULL = {{
  races: {n},
  predicted: {{
    label: "Before qualifying", sub: "the model uses its own predicted grid",
    rows: [
{r("b_predicted_quali", "model", "Model", ", model: true")}
{r("b_predicted_quali", "prior_standings", "Pick the points leader")}
{r("b_predicted_quali", "prior_constructor", "Pick the best team's lead driver")}
{r("b_predicted_quali", "prior_grid", "Pick the predicted pole sitter")}
    ],
  }},
  real: {{
    label: "After qualifying", sub: "the model is given the real starting grid",
    rows: [
{r("a_real_grid", "model", "Model", ", model: true")}
{r("a_real_grid", "prior_standings", "Pick the points leader")}
{r("a_real_grid", "prior_constructor", "Pick the best team's lead driver")}
{r("a_real_grid", "prior_grid", "Pick the pole sitter")}
    ],
  }},
}};"""

src = open(HOME, encoding="utf-8").read()
new = src
for name, block in (("BACKTEST_FULL", full), ("BACKTEST", backtest)):
    pat = re.compile(r"export const " + name + r" = \{.*?\n\};", re.S)
    assert pat.search(new), f"{name} block not found in homeModel.js"
    new = pat.sub(lambda m: block, new, count=1)

figs_path = os.path.join(d, "model_page_figures.json")
if not os.path.exists(figs_path):                       # the history folder has no figures file: compute it with the same script
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import importlib.util
    spec = importlib.util.spec_from_file_location("figs28", os.path.join(os.path.dirname(os.path.abspath(__file__)), "28_model_page_figures.py"))
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    figs = mod.figures(os.path.join(d, "backtest_rows.csv"))
else:
    figs = json.load(open(figs_path))
a, b = figs["a_real_grid"], figs["b_predicted_quali"]
gen = f"""// GENERATED by analysis/29_emit_frontend_figures.py from analysis/out/{'rolled' if args.source == 'rolled' else 'history/pre-roll-forward'}/ (backtest rows of the {n} races, 2025 R1-R24 and 2026 R1-R19).
// Do not edit by hand: re-run the script. Real grid = the model is given the real starting grid; predicted grid = the pre-qualifying path the site uses.
export const MODEL_FIGURES = {{
  races: {n},
  podiumAuc: {{ real: {a['podium_auc']:.3f}, predicted: {b['podium_auc']:.3f} }},
  winnerAuc: {{ real: {a['winner_auc']:.3f}, predicted: {b['winner_auc']:.3f} }},
  recallPct: {{ real: {100 * a['recall']:.1f}, predicted: {100 * b['recall']:.1f} }},
  precisionPct: {{ real: {100 * a['precision']:.1f}, predicted: {100 * b['precision']:.1f} }},
  top10GridOverlapPct: {100 * figs['top10_grid_overlap']:.1f},
}};
"""
cur_gen = open(GEN, encoding="utf-8").read() if os.path.exists(GEN) else None
if args.check:
    bad = []
    if new != src:
        bad.append("homeModel.js")
    if cur_gen is not None and gen != cur_gen:
        bad.append("modelFigures.generated.js")
    print("matches the files on disk" if not bad else f"DIFFERS: {', '.join(bad)}")
    sys.exit(1 if bad else 0)
open(HOME, "w", encoding="utf-8").write(new)
open(GEN, "w", encoding="utf-8").write(gen)
print(f"wrote {os.path.relpath(HOME, REPO)} (BACKTEST, BACKTEST_FULL) and {os.path.relpath(GEN, REPO)} from {args.source}")
